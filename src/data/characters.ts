const makeDemoCharacter = (role: NonNullable<Character['role']>, n: number): Character => {
  const tag = role === 'hero' ? 'HÉROE' : role === 'villain' ? 'VILLANO' : 'SECUNDARIO'
  const name = `DEMO ${tag} ${String(n).padStart(2, '0')}`
  return {
    name,
    image: demoImages[(n - 1) % demoImages.length],
    description: 'Personaje de muestra para demo.',
    slug: slugifyCharacterName(name),
    role,
  }
}

const normalizeRoleCounts = (list: Character[]) => {
  const desired: Record<NonNullable<Character['role']>, number> = {
    hero: 30,
    villain: 30,
    support: 30,
  }

  const byRole: Record<NonNullable<Character['role']>, Character[]> = {
    hero: [],
    villain: [],
    support: [],
  }

  for (const c of list) {
    const role = (c.role || 'support') as NonNullable<Character['role']>
    byRole[role].push({ ...c, role })
  }

  const out: Character[] = []
  for (const role of Object.keys(desired) as Array<NonNullable<Character['role']>>) {
    const items = byRole[role]

    const trimmed = items.slice(0, desired[role])
    out.push(...trimmed)

    const missing = desired[role] - trimmed.length
    for (let i = 1; i <= missing; i++) {
      out.push(makeDemoCharacter(role, trimmed.length + i))
    }
  }

  return out
}

