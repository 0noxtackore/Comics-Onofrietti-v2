export type Character = {
  name: string
  image: string
  description?: string
  slug: string
  role?: 'hero' | 'villain' | 'support'
  rank?: number
  realName?: string
  aliases?: string[]
  team?: string
  origin?: string
  powers?: string[]
  allies?: string[]
  enemies?: string[]
  gallery?: string[]
  appearances?: {
    comics?: string[]
  }
}

export const slugifyCharacterName = (name: string) =>
  name
    .trim()
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')

